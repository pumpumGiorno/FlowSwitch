{
    [FieldOffset(0)] public MOUSEINPUT mi;
    [FieldOffset(0)] public KEYBDINPUT ki;
}

[StructLayout(LayoutKind.Sequential)]
internal struct INPUT
{
    public uint type;
    public INPUTUNION u;

    public const uint KEYBOARD = 1;

    public static INPUT Key(ushort vk, bool up, nuint extraInfo, bool extended = false) => new()
    {
        type = KEYBOARD,
        u = new INPUTUNION
        {
            ki = new KEYBDINPUT
            {
                wVk = vk,
                dwFlags = (up ? Win32.KEYEVENTF_KEYUP : 0u) | (extended ? Win32.KEYEVENTF_EXTENDEDKEY : 0u),
                dwExtraInfo = extraInfo,
            },
        },
    };
}

